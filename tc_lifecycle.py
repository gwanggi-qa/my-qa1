"""Narrow, source-bound lifecycle checks with measured device evidence.

These are server-owned plans, not arbitrary shell commands generated by AI.
"""
import re
import time
import xml.etree.ElementTree as ET
import io
from PIL import Image

import ai_tc
import execution_results as records

PACKAGE = re.compile(r'^[A-Za-z][A-Za-z0-9_]*(?:\.[A-Za-z0-9_]+)+$')
PAGES = {'홈', '강의', '설정', '약관', '개인정보 처리방침', '고객센터', '계정탈퇴'}


def spec(step):
    if step.get('_contrast_pages') == ['홈', '설정', '약관', '개인정보 처리방침', '강의']:
        return {'kind': 'contrast', 'pages': list(step['_contrast_pages'])}
    lines = [re.sub(r'^\d+[.)]\s*', '', s.strip()).rstrip('.')
             for s in str(step.get('test_item', '')).splitlines() if s.strip()]
    expected = ai_tc.expected_text(step)
    if len(lines) == 2 and re.fullmatch(r'메인화면에서 시스템 뒤로가기를 한 번 수행한다', lines[0]):
        match = re.fullmatch(r'첫 뒤로가기 후 (\d+(?:\.\d+)?)초 안에 시스템 뒤로가기를 한 번 더 수행한다', lines[1])
        toast = re.search(r'「(.+?)」', expected)
        if match and toast and 1 <= float(match[1]) <= 5 and '두 번째 뒤로가기에 앱이 종료된다' in expected:
            # Unknown extra requirements must not disappear into the native verifier.
            clauses = [s for s in expected.splitlines() if s.strip()]
            if len(clauses) == 2 and '안내가 표시된다' in clauses[0]:
                return {'kind': 'timed_back', 'limit_s': float(match[1]), 'toast': toast[1]}
    if len(lines) == 3 and lines[0] == '앱을 실행한다' and lines[2] in {
            '앱을 종료하고 재실행하는 흐름을 반복하며 관찰한다', '앱을 종료하고 재실행한다'}:
        match = re.fullmatch(r'(.+) 화면으로 이동한다', lines[1])
        pages = [p.strip() for p in match[1].split(',')] if match else []
        if pages and set(pages) <= PAGES:
            if re.fullmatch(r'(?:관찰한 실행·화면 이동|이동한 실행·화면 이동|이동한 실행화면, 이동)·종료·재실행 구간에서 강제 종료나 (?:(?:응답 없음이)+|비정상 종료가) 발생하지 않는다\.?', expected.strip()):
                return {'kind': 'stability', 'pages': pages, 'cycles': 2 if '반복' in lines[2] else 1}
    return None


def plan(step, index):
    value = spec(step)
    if not value:
        return None
    text = ('홈·설정·약관·개인정보·강의 각각 진입 → 각 화면에서 원문 상태바 대비 검증'
            if value['kind'] == 'contrast' else
            '첫 Back → 안내 캡처 → 제한 시간 내 두 번째 Back → 런처 확인 → 현재 앱 복귀'
            if value['kind'] == 'timed_back' else
            f'현재 앱만 실행 → 지정 화면 순회 → 종료·재실행 {value["cycles"]}회 → 이번 구간 Crash/ANR 로그 검사 (탈퇴는 안내 화면만)')
    return {'index': index, 'blocked_reason': '', 'native': value,
            'actions': [{'procedure': 1, 'action': 'measured_device_check', 'target': text,
                         'direction': '', 'wait_ms': 0}]}


def decode(raw):
    return raw.decode('utf-8', errors='replace') if isinstance(raw, bytes) else str(raw)


def command(flow, *args):
    flow.guard()
    out, _, rc = flow.host.adb(*args, timeout_s=8)
    flow.guard()
    if rc:
        raise flow.host.BlockedStep('기기 측정 명령 실패: '+args[0])
    return decode(out)


def foreground(flow):
    text = command(flow, 'shell', 'dumpsys', 'activity', 'activities')
    match = re.search(r'(?:topResumedActivity|mResumedActivity|ResumedActivity)[^\n]*?\s([A-Za-z0-9_.]+)/', text)
    if not match:
        text = command(flow, 'shell', 'dumpsys', 'window')
        match = re.search(r'mCurrentFocus=[^\n]*?\s([A-Za-z0-9_.]+)/', text)
    if not match or not PACKAGE.fullmatch(match[1]):
        raise flow.host.BlockedStep('현재 전경 앱 패키지를 확인하지 못했습니다.')
    return match[1]


def component(flow, package=None):
    args = ['shell', 'cmd', 'package', 'resolve-activity', '--brief', '-a', 'android.intent.action.MAIN',
            '-c', 'android.intent.category.LAUNCHER' if package else 'android.intent.category.HOME']
    if package:
        args.append(package)
    text = command(flow, *args)
    candidates = re.findall(r'^([A-Za-z0-9_.]+/[A-Za-z0-9_.$]+)\s*$', text, re.M)
    if len(candidates) != 1 or (package and candidates[0].split('/')[0] != package):
        raise flow.host.BlockedStep('앱/런처 실행 컴포넌트를 유일하게 확인하지 못했습니다.')
    return candidates[0]


def input_command(flow, step, kind, *args):
    command(flow, *args)
    step.setdefault('_input_events', []).append({'action': kind, 'target': step['_app_package'],
        'status': 'adb_accepted', 'at': records.now()})


def launch(flow, step, activity, stop=False):
    with flow.host._adb_input_lock:
        if stop:
            input_command(flow, step, 'app_stop', 'shell', 'am', 'force-stop', step['_app_package'])
        input_command(flow, step, 'app_launch', 'shell', 'am', 'start', '-W', '-n', activity)
    if foreground(flow) != step['_app_package']:
        raise AssertionError('재실행 후 대상 앱이 전경에 표시되지 않습니다.')


def crash_records(text, since, package):
    """Return booleans only; do not persist potentially sensitive logcat payloads."""
    return any((m := re.match(r'\s*(\d+\.\d+)\s', line)) and float(m[1]) >= since
               and re.search(r'(?<![\w.])'+re.escape(package)+r'(?![\w.])', line)
               for line in text.splitlines())


def withdrawal_entry(xml):
    """An exact menu selector in settings, never a confirmation on the next page."""
    root = ET.fromstring(xml)
    nodes = list(root.iter('node'))
    label = lambda n: (n.get('text') or n.get('content-desc') or '').strip()
    labels = {label(n) for n in nodes}
    if not {'설정', '개인정보 처리방침', '고객센터', '계정탈퇴'} <= labels:
        raise ValueError('설정 메뉴 문맥이 아닙니다.')
    matches = [n for n in nodes if label(n) == '계정탈퇴' and n.get('enabled') != 'false']
    if len(matches) != 1:
        raise ValueError('탈퇴 안내 진입 메뉴가 유일하지 않습니다.')
    parents = {c:p for p in root.iter() for c in p}
    node = matches[0]
    while node in parents and node.get('clickable') != 'true':
        node = parents[node]
    if node.get('clickable') != 'true':
        raise ValueError('클릭 가능한 안내 메뉴가 아닙니다.')
    return node.get('bounds', '')


def open_withdrawal_information(flow, step):
    m = flow.host
    with m._adb_input_lock:
        flow.guard()
        if foreground(flow) != step['_app_package']:
            raise m.BlockedStep('안내 메뉴 진입 전 대상 앱이 변경됐습니다.')
        try:
            bounds = withdrawal_entry(m.dump_ui_xml())
            center = m.bounds_center(bounds)
        except (ValueError, ET.ParseError) as exc:
            raise m.BlockedStep('설정의 탈퇴 안내 진입 메뉴를 확인하지 못했습니다. 실제 탈퇴는 금지됩니다.') from exc
        if not center:
            raise m.BlockedStep('안내 메뉴의 유효한 화면 좌표가 없습니다.')
        input_command(flow, step, 'open_withdrawal_information', 'shell', 'input', 'tap', str(center['x']), str(center['y']))


def withdrawal_information_visible(xml):
    root = ET.fromstring(xml)
    labels = [(n.get('text') or n.get('content-desc') or '').strip() for n in root.iter('node')]
    # The prior settings menu alone is not evidence of entering the information page.
    if {'설정', '고객센터', '개인정보 처리방침'} <= set(labels):
        return False
    return (any(s in {'계정탈퇴','계정 탈퇴','회원탈퇴','회원 탈퇴'} for s in labels)
            and any(len(s) >= 15 and re.search(r'탈퇴|삭제|계정|회원', s) for s in labels))


def toast_text(flow, raw, stage):
    """Read the saved transient frame after the timing-critical input sequence."""
    schema = ai_tc.obj({'text': ai_tc.STR, 'bounds': {'type':'array','items':{'type':'integer'},'minItems':4,'maxItems':4}})
    reply, _ = flow.runtime_choice('Read only the transient Android toast at the bottom of this screenshot. '
        'Transcribe its visible text exactly. Do not infer missing characters. Return empty text and [0,0,0,0] '
        'if no readable toast. bounds must locate the toast in image pixels. No actions.', {}, schema, image_png=raw)
    with Image.open(io.BytesIO(raw)) as img:
        width, height = img.size
    x1,y1,x2,y2 = reply['bounds']
    if reply['text'] and not (0 <= x1 < x2 <= width and height*.5 <= y1 < y2 <= height):
        raise flow.host.BlockedStep('안내 문구 시각 근거 영역이 유효하지 않습니다.')
    stage['toast_visual_read'] = {'text':reply['text'], 'bounds':reply['bounds'], 'method':'ai-transcription'}
    return reply['text']


def execute(flow, step, case, value):
    m = flow.host
    # Recompute the spec, never trust a posted or modified native plan.
    if value != spec(step):
        raise m.BlockedStep('원문과 측정 실행 계획이 다릅니다.')
    package = foreground(flow)
    if package.startswith(('com.android.', 'com.samsung.android.', 'android.')):
        raise m.BlockedStep('시스템 앱에서는 종료·재실행 검증을 수행하지 않습니다.')
    activity, home = component(flow, package), component(flow)
    if package == home.split('/')[0]:
        raise m.BlockedStep('테스트 대상 앱을 먼저 열어주세요.')
    step['_app_package'] = package
    step['_source_bound'] = True
    stage = {'number': 0, 'source': step.get('test_item', ''), 'action': value['kind'], 'status': 'running',
             'actual': '', 'evidence': [], 'preconditions_verified': False, 'expectations_verified': False}
    case['stages'].append(stage)
    flow.phase(case['source']['tc_id']+' · 사전조건 준비', 'precondition')
    _, evidence = flow.navigate(step, step.get('precondition', ''), case, True)
    stage['evidence'].extend(evidence)
    stage['preconditions_verified'] = True
    if foreground(flow) != package:
        raise m.BlockedStep('사전조건 준비 중 대상 앱이 변경됐습니다.')
    if value['kind'] == 'timed_back':
        flow.phase(case['source']['tc_id']+' · Back 입력 간격 실측', 'device_input')
        with m._adb_input_lock:
            flow.guard()
            started = time.monotonic()
            input_command(flow, step, 'back', 'shell', 'input', 'keyevent', '4')
            if flow.cancel.wait(.15):
                flow.guard()
            raw = m.capture_screen_png()
            # Capturing is inside the measured window; AI/OCR runs only afterwards.
            if time.monotonic()-started >= value['limit_s']:
                raise m.BlockedStep('첫 Back 캡처 중 시간 한도를 초과해 두 번째 입력을 보내지 않았습니다.')
            input_command(flow, step, 'back', 'shell', 'input', 'keyevent', '4')
            elapsed = time.monotonic()-started
        path = m.QA_RESULTS_DIR/('tc-timed-toast-'+flow.id+'.png')
        path.write_bytes(raw)
        stage['evidence'].append({'file': path.name, 'url': m.qa_result_screenshot_url(path), 'label': '첫 Back 안내'})
        stage['timing'] = {'elapsed_upper_bound_s': elapsed, 'limit_s': value['limit_s'], 'clock': 'monotonic'}
        stage['evidence'].append(flow.evidence('두 번째 Back 후'))
        # Verify departure before restoring the app, even if OCR is unavailable.
        left = foreground(flow)
        launch(flow, step, activity)
        stage['evidence'].append(flow.evidence('테스트 앱 복귀'))
        if elapsed >= value['limit_s']:
            raise m.BlockedStep('입력 완료까지 실측 '+str(round(elapsed,3))+'초: 시간 조건 충족을 보장할 수 없습니다.')
        if left != home.split('/')[0]:
            raise AssertionError('두 번째 Back 후 기본 런처로 종료되지 않았습니다.')
        texts = m.ocr_screen_texts(raw)
        normalize = lambda s: re.sub(r'[^가-힣A-Za-z0-9]', '', s).lower()
        found = normalize(' '.join(t['text'] for t in texts))
        if normalize(value['toast']) not in found:
            found = normalize(toast_text(flow, raw, stage))
        if normalize(value['toast']) not in found:
            raise m.BlockedStep('첫 Back 안내 캡처에서 원문 문구를 확정하지 못했습니다. 런처 복귀와 시간 측정은 완료.')
        actual = f"첫 Back 안내 확인, 두 입력 완료 상한 {elapsed:.3f}초 < {value['limit_s']}초, 런처 종료 및 앱 복귀 확인"
    elif value['kind'] == 'contrast':
        for page in value['pages']:
            step['_supplements'] = 0
            step['_navigation_seen'] = []
            flow.phase(case['source']['tc_id']+' · 상태바 대비 검사 · '+page, 'verification')
            goal = {'홈':'메인화면', '강의':'기존 강의 재생 화면', '약관':'이용약관 본문 화면'}.get(page, page+' 화면')
            _, ev = flow.navigate(step, goal, case)
            stage['evidence'].extend(ev)
            # Normalize the two conditional clauses; the body theme is not the status bar background.
            text, ev = flow.check(step, '현재 화면의 상태바 아이콘이 상태바 자체의 배경과 구분되어 표시된다. '
                '상태바 배경이 흰색이면 아이콘이 흰색으로 묻히지 않고, 상태바 배경이 어두우면 아이콘이 어두운 색으로 묻히지 않는다. '
                '배경 조건은 상태바 자체의 배경에만 적용하며, 본문이나 하단 내비게이션 바의 색상은 이 조건의 배경이 아니다.')
            stage['evidence'].extend(ev)
            stage.setdefault('screen_checks', []).append({'screen':page,'status':'passed','reason':text})
        actual = '홈·설정·약관·개인정보·강의 5개 화면의 상태바 대비를 각 화면에서 확인. 조건부 어두운 배경은 실제 표시된 경우에만 검사.'
    else:
        since = float(command(flow, 'shell', 'date', '+%s').strip())
        # Verify log readers before actions; never clear shared device logs.
        command(flow, 'logcat', '-b', 'crash', '-d', '-v', 'epoch')
        command(flow, 'logcat', '-b', 'events', '-d', '-v', 'epoch', '-s', 'am_anr', 'am_crash')
        launch(flow, step, activity)
        for page in value['pages']:
            flow.phase(case['source']['tc_id']+' · 화면 순회 · '+page, 'device_input')
            # Per-destination bounded navigation, not an unbounded recovery loop.
            step['_supplements'] = 0
            step['_navigation_seen'] = []
            if page == '계정탈퇴':
                _, ev = flow.navigate(step, '설정 화면', case)
                stage['evidence'].extend(ev)
                open_withdrawal_information(flow, step)
                if flow.cancel.wait(.35):
                    flow.guard()
                if not withdrawal_information_visible(m.dump_ui_xml()):
                    raise m.BlockedStep('탈퇴 안내의 제목·설명 문구를 확인하지 못했습니다. 실제 탈퇴는 실행하지 않았습니다.')
                ev = [flow.evidence('탈퇴 안내 제목·설명 확인, 실제 탈퇴 미실행')]
            else:
                goal = {'홈':'메인화면', '강의':'기존 강의 재생 화면', '약관':'이용약관 본문 화면'}.get(page, page+' 화면')
                _, ev = flow.navigate(step, goal, case)
            stage['evidence'].extend(ev)
            stage['evidence'].append(flow.evidence(page))
            if foreground(flow) != package:
                raise AssertionError('화면 순회 중 대상 앱이 전경에서 사라졌습니다: '+page)
        for cycle in range(value['cycles']):
            flow.phase(case['source']['tc_id']+f' · 종료·재실행 {cycle+1}/{value["cycles"]}', 'device_input')
            launch(flow, step, activity, stop=True)
            stage['evidence'].append(flow.evidence('재실행 '+str(cycle+1)))
            # UI dump requires the resumed app to respond; read failures do not pass.
            if not m.dump_ui_xml():
                raise m.BlockedStep('재실행 후 UI 응답을 확인하지 못했습니다.')
        crash = command(flow, 'logcat', '-b', 'crash', '-d', '-v', 'epoch')
        events = command(flow, 'logcat', '-b', 'events', '-d', '-v', 'epoch', '-s', 'am_anr', 'am_crash')
        if crash_records(crash, since, package) or crash_records(events, since, package):
            raise AssertionError('이번 관찰 구간의 대상 앱 Crash/ANR 로그가 확인됐습니다.')
        actual = f'지정 화면 순회 및 종료·재실행 {value["cycles"]}회 완료. 이번 관찰 구간 대상 앱 Crash/ANR 로그 없음; 전경/UI 응답 확인. 탈퇴 실행 없음.'
        stage['log_observation'] = {'device_start_epoch': since, 'package': package, 'crash_anr_found': False}
    stage.update(status='passed', actual=actual, expectations_verified=True)
    for entry in case['stages']:
        if entry.get('status') == 'executed':
            entry.update(status='passed', expectations_verified=True)
    return actual
