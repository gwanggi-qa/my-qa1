// Only the disposable fixture server, never the production database/device.
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
const fs=require('node:fs');
const output=path.resolve(__dirname,'../qa_results/draft-ui');
fs.mkdirSync(output,{recursive:true});
(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true});
  const context=await browser.newContext({viewport:{width:1440,height:1000}});
  const page=await context.newPage(),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  try{
    await page.goto('http://localhost:5015/app-analysis',{waitUntil:'networkidle'});
    const templateDownload=page.waitForEvent('download');
    await page.locator('#draft-template').click();
    await (await templateDownload).saveAs(path.join(output,'testcase-template.xlsx'));
    await page.locator('#figma-url').fill('https://www.figma.com/design/fixture/Learning?node-id=1-2');
    await page.locator('#figma-import').click();
    await page.waitForFunction(()=>/가져오기 완료|동일한 버전/.test(document.querySelector('#figma-status').textContent));
    await page.waitForFunction(()=>document.querySelectorAll('#reference-list button').length===1);
    assert.equal(await page.locator('#reference-list button').count(),1);
    await page.waitForFunction(()=>document.querySelector('#reference-content img')?.naturalWidth>0);
    await page.locator('#reference-kind').selectOption('requirements');
    await page.locator('#reference-file').setInputFiles({name:'synthetic-requirements.md',mimeType:'text/markdown',buffer:Buffer.from('# Synthetic QA fixture\nThe learning management screen must show LC results and RC results together.\nNo score calculation or user accounts are involved.\nThis is synthetic data for integration testing only.')});
    await page.locator('#reference-upload').click();
    await page.waitForFunction(()=>document.querySelectorAll('#draft-sources input').length===2);
    for(const checkbox of await page.locator('#draft-sources input').all())await checkbox.check();
    await page.locator('#draft-scope').fill('학습 관리 화면에 LC 및 RC 결과 영역이 함께 표시되는지 확인하는 TC 1개');
    await page.locator('#draft-count').fill('1');
    await page.locator('#draft-images').check();
    await page.locator('#draft-preview').click();
    await page.waitForFunction(()=>!document.querySelector('#draft-consent').disabled);
    assert.match(await page.locator('#draft-context').innerText(),/evidence/);
    assert.equal(await page.locator('#draft-input-images img').count(),1);
    await page.locator('#draft-consent').check();
    await page.locator('#draft-generate').click();
    await page.waitForFunction(()=>{const s=document.querySelector('#draft-message').textContent;return s.includes('초안 생성 완료')||s.includes('생성 실패');},null,{timeout:180000});
    const generation=await page.locator('#draft-message').innerText();
    assert.ok(generation.includes('초안 생성 완료'),generation);
    assert.ok(await page.locator('#draft-case option').count()>=1);
    assert.equal(await page.locator('#case-review-status').inputValue(),'draft');
    assert.equal(await page.locator('#case-depth1').inputValue(),'학습 관리');
    assert.equal(await page.locator('#case-test_type').inputValue(),'UI-UX');
    await page.locator('#case-depth3').fill('LC/RC 결과 카드');
    assert.equal(await page.locator('#draft-export').isDisabled(),true);
    await page.locator('#case-title').fill('합성 자료 검증: LC·RC 표시');
    await page.locator('#case-review-status').selectOption('approved');
    await page.locator('#case-save').click();
    await page.waitForFunction(()=>document.querySelector('#draft-message').textContent.includes('검토 저장 완료'));
    assert.equal(await page.locator('#case-depth3').inputValue(),'LC/RC 결과 카드');
    const download=page.waitForEvent('download');
    await page.locator('#draft-export').click();
    await (await download).saveAs(path.join(output,'reviewed-testcases.xlsx'));
    await page.screenshot({path:path.join(output,'desktop.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(output,'mobile.png'),fullPage:true});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    assert.ok(await page.locator('button').evaluateAll(es=>es.every(e=>!e.clientWidth||e.scrollWidth<=e.clientWidth+1)));
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({generation,figma:'mocked',review:true,export:true,mobile:true,errors}));
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
